namespace FlexRt.Model.Panel.Screens;

/// <summary>Режим General кнопки, установленный на компиляциях TP700 Comfort V21.</summary>
public enum ButtonMode
{
    /// <summary>Текст.</summary>
    Text,
    /// <summary>Картинка.</summary>
    Graphic,
    /// <summary>Текстовый список.</summary>
    TextList,
    /// <summary>Графический список.</summary>
    GraphicList,
    /// <summary>Картинка и текст.</summary>
    GraphicAndText,
    /// <summary>Невидимая кнопка.</summary>
    Invisible
}
